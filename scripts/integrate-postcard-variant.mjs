// Integrate a reviewed alternate scene while preserving the country's prior files.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const [manifestPath,basename,previousMetadataName]=process.argv.slice(2);
if(!manifestPath||!/^[a-z][a-z0-9-]+$/.test(basename??'')||!/^[a-z][a-z0-9-]+\.json$/.test(previousMetadataName??''))throw Error('Pass manifest, unique asset basename and prior metadata filename');
const entries=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
if(entries.length!==1)throw Error('Alternate-scene integration accepts exactly one reviewed country');
const entry=entries[0],code=entry.code;
if(!/^[A-Z]{2}$/.test(code)||!entry.prompt||!entry.inspection||!entry.landmark||!entry.landmarkKo||!entry.sources?.length)throw Error('Incomplete reviewed scene');
const generationRoot=path.resolve(root,'../postcard-generation');
if(!path.resolve(entry.path).startsWith(generationRoot+path.sep))throw Error('Original must be inside generation workspace');
const metadataRoot=path.join(root,'artwork/postcards'),metadataPath=path.join(metadataRoot,code.toLowerCase()+'.json');
const priorMetadata=JSON.parse(fs.readFileSync(metadataPath));
const dbPath=path.join(root,'src/postcard-assets.json'),db=JSON.parse(fs.readFileSync(dbPath));
if(db[code]?.image!==priorMetadata.webImage)throw Error('Prior app binding and metadata disagree');
const filename=basename+'.webp',appFile=path.join(root,'public/assets/postcards',filename),exportFile=path.join(generationRoot,'export',filename),priorPath=path.join(metadataRoot,previousMetadataName);
for(const file of [appFile,exportFile,priorPath])if(fs.existsSync(file))throw Error('Preserve existing file: '+file);
const sharpPath=process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES?pathToFileURL(path.join(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES,'sharp/dist/index.mjs')).href:'sharp';
const {default:sharp}=await import(sharpPath);
const info=await sharp(entry.path).metadata();
if(info.width<1000||info.width*2!==info.height*3)throw Error('Require high-quality 3:2 original');
fs.copyFileSync(metadataPath,priorPath);
await sharp(entry.path).resize({width:1024,withoutEnlargement:true}).webp({quality:87,effort:6}).toFile(appFile);
await sharp(entry.path).webp({quality:94,effort:6}).toFile(exportFile);
db[code]={image:'/assets/postcards/'+filename,landmark:entry.landmark,landmarkKo:entry.landmarkKo};
const {path:originalPath,...record}=entry;
fs.writeFileSync(metadataPath,JSON.stringify({...record,originalFile:path.basename(originalPath),width:info.width,height:info.height,generator:'built-in image_gen',reviewedAt:'2026-10-01',webImage:db[code].image,exportFile:filename,previousSceneMetadata:previousMetadataName},null,2)+'\n');
fs.writeFileSync(dbPath,JSON.stringify(db,null,2)+'\n');
console.log(code+': alternate scene connected; previous app image, export and metadata preserved');
